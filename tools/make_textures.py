#!/usr/bin/env python3
"""Generate the house's material textures offline: seamless colour + normal (+ roughness) maps at real-world
scale, written to assets/tex/ and listed in assets/tex/manifest.json, where the app picks them up in place of
its small in-browser canvas textures (see "Photo textures" in textures.js).

    python3 tools/make_textures.py              # everything
    python3 tools/make_textures.py oak quartz   # just these

All maps tile seamlessly: noise is made in the frequency domain (FFT), so it wraps at the edges, and board /
course / tile layouts are laid out modulo the tile size. Each set's average colour is stored so the app can tint
it to any finish colour. These are original, procedurally generated images (no third-party content).
Needs numpy and Pillow.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'assets', 'tex')


# ── Building blocks ─────────────────────────────────────────────────────────────────────────────
def rng(seed):
    return np.random.default_rng(seed)


def spectral(n, scale, seed, aniso=(1.0, 1.0), beta=2.0, m=None):
    """Seamless noise, n×n (or n×m). `scale` = feature size in px; aniso stretches features (x, y);
    beta shapes the spectrum (higher = smoother). Returns roughly 0..1."""
    m = m or n
    r = rng(seed)
    white = r.standard_normal((m, n))
    fy = np.fft.fftfreq(m)[:, None] * aniso[1]
    fx = np.fft.fftfreq(n)[None, :] * aniso[0]
    f = np.sqrt(fx * fx + fy * fy)
    f0 = 1.0 / max(scale, 1.0)
    filt = 1.0 / (1.0 + (f / f0) ** beta)
    out = np.real(np.fft.ifft2(np.fft.fft2(white) * filt))
    out = (out - out.mean()) / (out.std() + 1e-9)
    return np.clip(out * 0.18 + 0.5, 0, 1)


def fbm(n, scale, seed, octaves=4, aniso=(1.0, 1.0), m=None):
    acc, amp, tot = 0, 1.0, 0
    for o in range(octaves):
        acc = acc + amp * spectral(n, scale / (2 ** o), seed + o * 101, aniso, m=m)
        tot += amp
        amp *= 0.5
    return acc / tot


def sample(img, x, y):
    """Bilinear sample with wrap. img (h,w[,c]); x,y float arrays in px."""
    h, w = img.shape[:2]
    x0 = np.floor(x).astype(int); y0 = np.floor(y).astype(int)
    fx = (x - x0)[..., None] if img.ndim == 3 else x - x0
    fy = (y - y0)[..., None] if img.ndim == 3 else y - y0
    x0 %= w; y0 %= h; x1 = (x0 + 1) % w; y1 = (y0 + 1) % h
    a = img[y0, x0] * (1 - fx) + img[y0, x1] * fx
    b = img[y1, x0] * (1 - fx) + img[y1, x1] * fx
    return a * (1 - fy) + b * fy


def normal_map(h, strength):
    """Height (0..1) → OpenGL-convention normal map (three.js), wrapping at the edges."""
    dx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) * 0.5
    dy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) * 0.5
    nx, ny, nz = -dx * strength, dy * strength, np.ones_like(h)
    l = np.sqrt(nx * nx + ny * ny + nz * nz)
    return np.stack([nx / l, ny / l, nz / l], -1) * 0.5 + 0.5


def hex_rgb(h):
    h = h.lstrip('#'); return np.array([int(h[i:i + 2], 16) for i in (0, 2, 4)], float) / 255


def shade(rgb, *amount):
    """Multiply an RGB colour (0..1) by per-pixel factors."""
    out = rgb[None, None, :] * np.ones(amount[0].shape + (3,))
    for a in amount:
        out = out * a[..., None]
    return out


def to_img(a):
    return Image.fromarray(np.clip(a * 255 + 0.5, 0, 255).astype(np.uint8))


def save_set(name, color, height=None, nstrength=4.0, rough=None, ft=4.0, size=None):
    """Write colour / normal / roughness JPEGs and return a manifest entry."""
    os.makedirs(OUT, exist_ok=True)
    entry = {'ft': round(ft, 4), 'license': 'CC0 (generated by tools/make_textures.py)'}
    im = to_img(color)
    if size and im.size[0] != size:
        im = im.resize((size, size), Image.LANCZOS)
    im.save(os.path.join(OUT, f'{name}_map.jpg'), quality=88, optimize=True)
    entry['map'] = f'{name}_map.jpg'
    avg = np.asarray(im, float).reshape(-1, 3).mean(0)
    entry['avg'] = '#%02x%02x%02x' % tuple(int(round(v)) for v in avg)
    if height is not None:
        nm = to_img(normal_map(height, nstrength))
        if size and nm.size[0] != size:
            nm = nm.resize((size, size), Image.LANCZOS)
        nm.save(os.path.join(OUT, f'{name}_nor.jpg'), quality=90, optimize=True)
        entry['normal'] = f'{name}_nor.jpg'
    if rough is not None:
        rm = to_img(np.repeat(rough[..., None], 3, -1)).convert('L')
        if size and rm.size[0] != size:
            rm = rm.resize((size, size), Image.LANCZOS)
        rm.save(os.path.join(OUT, f'{name}_rough.jpg'), quality=85, optimize=True)
        entry['rough'] = f'{name}_rough.jpg'
    return entry


def wood_grain(n, m, seed, along_x=True, ring=24.0, warp=18.0, fine=0.35):
    """Flat-sawn grain: long latewood lines that wander and arch along the board, plus fine streaks and pores.
    0..1, light = earlywood."""
    yy, xx = np.mgrid[0:m, 0:n].astype(float)
    a = (6.0, 0.7) if along_x else (0.7, 6.0)
    w1 = spectral(n, 120, seed, aniso=a, m=m) - 0.5                 # slow wander of the whole figure
    w2 = spectral(n, 30, seed + 7, aniso=a, m=m) - 0.5              # tighter waviness
    coord = (yy if along_x else xx) + w1 * ring * 7 + w2 * warp
    f = (coord / ring) % 1.0
    late = np.exp(-((f - 0.5) ** 2) / 0.012)                         # thin dark latewood band once per ring
    soft = 0.5 + 0.5 * np.cos(f * 2 * np.pi)                          # gentle earlywood → latewood shading
    streak = spectral(n, 2.5, seed + 13, aniso=(30, 1) if along_x else (1, 30), m=m)
    pores = spectral(n, 1.1, seed + 17, aniso=(14, 1) if along_x else (1, 14), m=m)
    return np.clip(1 - 0.42 * late - 0.12 * soft - fine * 0.5 * (streak - 0.5) - 0.12 * (pores - 0.5), 0, 1)


