def oak():
    """Floor: 7" white-oak boards, random lengths, eased edges. 8 boards across = 4'8"."""
    N = 1024; ft = 8 * 7 / 12; ppf = N / ft
    r = rng(1); rows = 8; bw = N / rows
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // bw).astype(int)
    tone = np.ones((N, N)); grain = np.ones((N, N)); height = np.ones((N, N))
    board_id = np.zeros((N, N), int)
    base_grain = [wood_grain(N, N, 100 + k, True, ring=18 + 14 * r.random(), warp=10 + 8 * r.random(), fine=0.25) for k in range(6)]
    for i in range(rows):
        sel = row == i
        # joints at random positions along the (wrapping) row
        joints = np.sort(r.uniform(0, N, r.integers(1, 3)))
        seg = np.searchsorted(joints, xx[sel]) % len(joints)
        for s in range(len(joints)):
            bsel = np.zeros((N, N), bool); idx = np.where(sel)
            mask = seg == s
            bsel[idx[0][mask], idx[1][mask]] = True
            bid = i * 10 + s; board_id[bsel] = bid
            tone[bsel] = float(np.clip(1 + r.normal(0, 0.08), 0.86, 1.1))
            g = base_grain[r.integers(0, 6)]
            ox, oy = r.integers(0, N), r.integers(0, N)
            grain[bsel] = np.roll(np.roll(g, oy, 0), ox, 1)[bsel]
        # eased edges along the long sides
        d = np.minimum((yy - i * bw) % bw, bw - (yy - i * bw) % bw)
        height = np.where(sel, np.minimum(height, np.clip(d / 3.0, 0, 1)), height)
        for j in joints:
            dj = np.abs((xx - j + N / 2) % N - N / 2)
            height = np.where(sel, np.minimum(height, np.clip(dj / 2.5, 0, 1)), height)
    mottle = fbm(N, 180, 3) - 0.5
    lum = tone * (0.78 + 0.32 * grain) * (1 + 0.1 * mottle)
    base = hex_rgb('#c4a47e')
    warm = (grain - 0.5)[..., None] * np.array([0.05, 0.015, -0.03])
    col = shade(base, lum) * (0.55 + 0.45 * height[..., None]) + warm
    h = height * 0.7 + grain * 0.3
    rough = np.clip(0.42 + 0.18 * (1 - grain) + 0.3 * (1 - height), 0, 1)
    return save_set('oak', col, h, 3.0, rough, ft)


def wood():
    """Furniture veneer: fine continuous grain, neutral mid brown (tinted per piece). 3 ft."""
    N = 512
    g = wood_grain(N, N, 200, True, ring=9, warp=10)
    lum = 0.82 + 0.3 * g
    col = shade(hex_rgb('#8a6a4a'), lum)
    return save_set('wood', col, g, 1.5, None, 3.0)


def butcher():
    """Butcher-block counter: 1½" maple strips glued edge to edge. 3 ft."""
    N = 512; ft = 3.0; strips = 24; sw = N / strips
    r = rng(5); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // sw).astype(int)
    tone = np.array([1 + r.normal(0, 0.09) for _ in range(strips)])[row]
    g = wood_grain(N, N, 300, True, ring=6, warp=6)
    seam = np.clip(np.minimum(yy % sw, sw - yy % sw) / 1.2, 0, 1)
    col = shade(hex_rgb('#b98b5a'), tone * (0.85 + 0.25 * g)) * (0.85 + 0.15 * seam[..., None])
    return save_set('butcher', col, seam * 0.5 + g * 0.5, 1.5, None, ft)


def siding():
    """Painted clapboard: 4" exposure, shadow line under each lap, faint grain through the paint. 4 ft."""
    N = 1024; ft = 4.0; courses = 12; ch = N / courses
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    t = (yy % ch) / ch                                            # 0 at the top of a course → 1 at the butt
    lap = np.clip(t * 1.0, 0, 1) ** 1.3                          # board thickens toward the bottom edge
    shadow = 1 - 0.55 * np.clip((t - 0.9) / 0.1, 0, 1)            # dark line under the lap
    r = rng(9); row = (yy // ch).astype(int)
    joints = np.array([r.uniform(0, N) for _ in range(courses)])[row]
    dj = np.abs((xx - joints + N / 2) % N - N / 2)
    butt = np.clip(dj / 1.5, 0, 1)
    grain = wood_grain(N, N, 400, True, ring=8, warp=6, fine=0.2)
    paint = fbm(N, 90, 11) - 0.5
    lum = (0.9 + 0.06 * grain + 0.05 * paint) * shadow * (0.8 + 0.2 * butt) * (0.92 + 0.08 * (1 - t))
    col = shade(hex_rgb('#d4d4d0'), lum)
    h = lap * 0.85 + grain * 0.04 + (1 - butt) * -0.3
    return save_set('siding', col, np.clip(h, 0, 1), 6.0, None, ft)


def shakes(name, base, exposure_in, ft, seed, weathered):
    """Cedar shakes (walls) / architectural shingles (roof): courses of tabs of varying width."""
    N = 1024; ppf = N / ft; ch = exposure_in / 12 * ppf
    courses = int(round(N / ch)); ch = N / courses
    r = rng(seed); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // ch).astype(int); t = (yy % ch) / ch
    tone = np.ones((N, N)); h = np.zeros((N, N)); gapmask = np.ones((N, N))
    tid = np.zeros((N, N))
    for i in range(courses):
        sel = row == i
        edges = []; x = r.uniform(0, N)
        while len(edges) == 0 or (x - edges[0]) < N:
            edges.append(x); x += r.uniform(0.25, 0.85 if weathered else 1.2) * ppf * (0.6 if weathered else 1.0)
        edges = np.array(edges) % N; edges.sort()
        k = np.searchsorted(edges, xx[sel]) % len(edges)
        shade_k = 1 + r.normal(0, 0.12 if weathered else 0.08, len(edges))
        tone[sel] = shade_k[k]
        tid[sel] = k + i * 100
        for e in edges:
            de = np.abs((xx[sel] - e + N / 2) % N - N / 2)
            gapmask[sel] = np.minimum(gapmask[sel], np.clip(de / (2.2 if weathered else 1.6), 0, 1))
    butt = np.clip((t - 0.86) / 0.14, 0, 1)
    h = (t ** 1.2) * gapmask
    if weathered:
        grain = spectral(N, 2.0, seed + 3, aniso=(1, 20))
        lum = tone * (0.8 + 0.35 * grain) * (1 - 0.6 * butt) * (0.55 + 0.45 * gapmask)
        h = h + (grain - 0.5) * 0.25
    else:
        gran = spectral(N, 0.9, seed + 5)
        lum = tone * (0.78 + 0.4 * gran) * (1 - 0.65 * butt) * (0.5 + 0.5 * gapmask)
        h = h + (gran - 0.5) * 0.12
    col = shade(hex_rgb(base), lum)
    rough = None if weathered else np.clip(0.85 + 0.1 * (gran - 0.5), 0, 1)
    return save_set(name, col, np.clip(h, 0, 1), 7.0, rough, ft)


def brick():
    """Running-bond brick, ⅜" mortar, 18 courses per 4 ft."""
    N = 1024; ft = 4.0; ppf = N / ft; courses = 18; ch = N / courses; bl = 8.375 / 12 * ppf
    cols = int(round(N / bl)); bl = N / cols
    r = rng(21); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // ch).astype(int)
    xo = (xx + (row % 2) * bl / 2) % N
    colm = (xo // bl).astype(int)
    mortar_px = 0.375 / 12 * ppf
    my = np.minimum(yy % ch, ch - yy % ch); mx = np.minimum(xo % bl, bl - xo % bl)
    inside = np.clip((np.minimum(mx, my) - mortar_px / 2) / 2.0, 0, 1)
    tone = 1 + r.normal(0, 0.12, (courses, cols + 1))[row, colm]
    hue = r.normal(0, 0.05, (courses, cols + 1))[row, colm]
    rough_s = fbm(N, 6, 23)
    brick_rgb = shade(hex_rgb('#8e3b2c'), tone * (0.85 + 0.3 * rough_s)) + hue[..., None] * np.array([0.06, 0.02, 0])
    mortar = shade(hex_rgb('#b8b0a4'), 0.9 + 0.2 * fbm(N, 3, 24))
    col = brick_rgb * inside[..., None] + mortar * (1 - inside[..., None])
    h = inside * 0.8 + rough_s * 0.2
    return save_set('brick', col, h, 6.0, None, ft)


def stone():
    """Stacked ledgestone (fireplace): long thin stones of mixed greys and tans, deep shadowed joints. 3 ft."""
    N = 1024; ft = 3.0; ppf = N / ft
    r = rng(31); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    h = np.zeros((N, N)); col = np.zeros((N, N, 3))
    palette = [hex_rgb(c) for c in ['#8f8a82', '#a69a86', '#6f6c68', '#b3a896', '#7d6f62', '#9c958c', '#8a7b6a']]
    y = 0.0
    tex = fbm(N, 10, 33); fine = spectral(N, 1.5, 34)
    while y < N:
        rh = r.uniform(1.5, 3.2) / 12 * ppf
        if y + rh > N: rh = N - y
        x = r.uniform(0, N); start = x
        while x - start < N:
            sl = r.uniform(5, 16) / 12 * ppf
            sel_y = (yy >= y) & (yy < y + rh)
            dx = (xx - x) % N
            sel = sel_y & (dx < sl)
            # rounded stone face: higher in the middle, falls off at the edges
            ex = np.minimum(dx, sl - dx) / (sl / 2); ey = np.minimum(yy - y, y + rh - yy) / (rh / 2)
            face = np.clip(np.minimum(ex * 3, ey * 2.2), 0, 1) ** 0.6
            c = palette[r.integers(0, len(palette))] * (1 + r.normal(0, 0.06))
            h = np.where(sel, face * (0.7 + r.uniform(0, 0.3)), h)
            col = np.where(sel[..., None], c[None, None, :] * (0.8 + 0.35 * tex[..., None]), col)
            x += sl
        y += rh
    h = h + (fine - 0.5) * 0.12 + (tex - 0.5) * 0.15
    col = col * (0.35 + 0.65 * np.clip(h * 1.3, 0, 1))[..., None]
    return save_set('stone', col, np.clip(h, 0, 1), 9.0, None, ft)


def quartz():
    """White quartz: a few soft, long grey veins drifting across, faint cloudiness and sparkle; glossy. 4 ft."""
    N = 1024; ft = 4.0
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    w = spectral(N, 200, 41, beta=4.0) - 0.5                       # smooth fields → smooth vein curves
    w2 = spectral(N, 60, 42, beta=4.0) - 0.5
    v = np.sin((xx * 0.7 + yy * 0.3) / N * 2 * np.pi * 2 + w * 1.0 + w2 * 0.25)   # warp kept weaker than the trend: no loops
    vein = np.exp(-(v * v) / 0.02) * (0.5 + 0.5 * spectral(N, 50, 45, beta=4.0))   # soft band whose strength varies along it
    v2 = np.sin((xx * -0.25 + yy * 0.9) / N * 2 * np.pi * 1 + w2 * 0.35 + w * 0.5)
    vein2 = np.exp(-(v2 * v2) / 0.008) * 0.45
    cloud = fbm(N, 160, 43) - 0.5
    spark = (spectral(N, 0.6, 44) > 0.78).astype(float)
    lum = 0.975 + 0.035 * cloud - 0.16 * vein - 0.1 * vein2 + 0.02 * spark
    col = shade(hex_rgb('#efeeea'), lum) + (vein[..., None] * np.array([0.0, -0.004, -0.008]))
    rough = np.clip(0.15 + 0.04 * cloud + 0.04 * vein, 0, 1)
    return save_set('quartz', col, 0.5 + 0.04 * cloud, 0.4, rough, ft)


def tile():
    """12×24" porcelain floor tile, ⅛" grout, staggered by a third, subtle stone look. 4 ft."""
    N = 1024; ft = 4.0; ppf = N / ft; tw, th = 2 * ppf, 1 * ppf
    r = rng(51); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // th).astype(int)
    xo = (xx + (row % 3) * tw / 3) % N
    colm = (xo // tw).astype(int)
    g = 0.125 / 12 * ppf
    dy = np.minimum(yy % th, th - yy % th); dx = np.minimum(xo % tw, tw - xo % tw)
    inside = np.clip((np.minimum(dx, dy) - g / 2) / 1.5, 0, 1)
    tone = 1 + r.normal(0, 0.035, (8, 4))[row % 8, colm % 4]
    stonel = fbm(N, 70, 53) - 0.5
    col_t = shade(hex_rgb('#9a9893'), tone * (1 + 0.1 * stonel))
    grout = shade(hex_rgb('#6f6c66'), np.ones((N, N)))
    col = col_t * inside[..., None] + grout * (1 - inside[..., None])
    rough = np.clip(0.38 + 0.08 * stonel + 0.45 * (1 - inside), 0, 1)
    return save_set('tile', col, inside * 0.9 + stonel * 0.05, 3.0, rough, ft)


def subway():
    """3×6" glossy subway tile with bevelled edges, running bond. 2 ft."""
    N = 512; ft = 2.0; ppf = N / ft; tw, th = 0.5 * ppf, 0.25 * ppf
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // th).astype(int)
    xo = (xx + (row % 2) * tw / 2) % N
    dy = np.minimum(yy % th, th - yy % th); dx = np.minimum(xo % tw, tw - xo % tw)
    d = np.minimum(dx, dy)
    g = 0.0625 / 12 * ppf
    bevel = np.clip((d - g / 2) / 3.0, 0, 1)
    wav = spectral(N, 20, 61) - 0.5
    col = shade(hex_rgb('#f2f1ee'), (0.9 + 0.1 * bevel) * (1 + 0.03 * wav))
    col = np.where((d < g / 2)[..., None], hex_rgb('#d9d6cf')[None, None, :], col)
    rough = np.clip(0.12 + 0.6 * (d < g / 2), 0, 1)
    return save_set('subway', col, bevel * 0.9 + wav * 0.05, 4.0, rough, ft)


def carpet():
    N = 512; ft = 2.0
    loops = spectral(N, 0.9, 71); tufts = spectral(N, 3, 72)
    lum = 0.82 + 0.25 * loops + 0.1 * (tufts - 0.5)
    col = shade(hex_rgb('#a39a8c'), lum)
    return save_set('carpet', col, loops * 0.7 + tufts * 0.3, 3.0, None, ft)


def fabric():
    """Upholstery linen: over-under weave with slubby threads. 1.5 ft."""
    N = 512; ft = 1.5; ppf = N / ft; per = 2.6                    # px per thread
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    per = N / round(N / per)
    wx = 0.5 + 0.5 * np.cos(xx / per * np.pi * 2); wy = 0.5 + 0.5 * np.cos(yy / per * np.pi * 2)
    check = ((np.floor(xx / per) + np.floor(yy / per)) % 2)
    weave = np.where(check > 0, wx, wy)
    slub = spectral(N, 6, 81, aniso=(1, 8)) * 0.5 + spectral(N, 6, 82, aniso=(8, 1)) * 0.5
    lum = 0.8 + 0.18 * weave + 0.12 * (slub - 0.5)
    col = shade(hex_rgb('#c9c2b6'), lum)
    return save_set('fabric', col, weave * 0.7 + slub * 0.3, 2.0, None, ft)


def leather():
    """Pebbled leather grain (cells), with a little sheen variation. 2.5 ft."""
    N = 512; ft = 2.5
    r = rng(91); pts = r.uniform(0, N, (2200, 2))
    yy, xx = np.mgrid[0:N, 0:N].astype(float)
    d1 = np.full((N, N), 1e9); d2 = np.full((N, N), 1e9)
    for px, py in pts:
        dx = np.abs(xx - px); dx = np.minimum(dx, N - dx)
        dy = np.abs(yy - py); dy = np.minimum(dy, N - dy)
        d = dx * dx + dy * dy
        d2 = np.where(d < d1, d1, np.minimum(d2, d)); d1 = np.minimum(d1, d)
    edge = np.clip((np.sqrt(d2) - np.sqrt(d1)) / 2.0, 0, 1)
    mott = fbm(N, 60, 92) - 0.5
    col = shade(hex_rgb('#6b4a35'), (0.9 + 0.1 * edge) * (1 + 0.12 * mott))
    return save_set('leather', col, edge, 2.5, None, ft)


def deck():
    """Weathered deck boards: 5½" wide, ¼" gaps, end joints. 4 ft."""
    N = 1024; ft = 4.0; ppf = N / ft
    boards = int(round(ft * 12 / 5.75)); bw = N / boards
    r = rng(101); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    row = (yy // bw).astype(int)
    tone = 1 + r.normal(0, 0.08, boards)[row]
    gap = 0.25 / 12 * ppf
    d = np.minimum(yy % bw, bw - yy % bw)
    inside = np.clip((d - gap / 2) / 1.5, 0, 1)
    joints = r.uniform(0, N, boards)[row]
    dj = np.abs((xx - joints + N / 2) % N - N / 2)
    inside = inside * np.clip(dj / 1.2, 0, 1)
    g = wood_grain(N, N, 110, True, ring=7, warp=8, fine=0.5)
    weather = fbm(N, 25, 111)
    col = shade(hex_rgb('#9c8f7e'), tone * (0.8 + 0.3 * g) * (0.9 + 0.2 * weather)) * (0.2 + 0.8 * inside[..., None])
    rough = np.clip(0.8 + 0.15 * (1 - inside), 0, 1)
    return save_set('deck', col, inside * 0.8 + g * 0.2, 4.0, rough, ft)


def concrete():
    N = 512; ft = 8.0
    m = fbm(N, 120, 121, 5); p = spectral(N, 0.8, 122); s = (spectral(N, 1.5, 123) > 0.78).astype(float)
    col = shade(hex_rgb('#a7a49e'), (0.95 + 0.1 * (m - 0.5) * 2) * (0.96 + 0.06 * p) - 0.04 * s)
    return save_set('concrete', col, m * 0.5 + p * 0.5, 1.5, None, ft)


def asphalt():
    N = 512; ft = 6.0
    agg = spectral(N, 1.1, 131); big = fbm(N, 80, 132)
    stones = (spectral(N, 1.6, 133) > 0.7).astype(float)
    col = shade(hex_rgb('#4a4a4c'), (0.85 + 0.35 * agg) * (0.92 + 0.16 * big) + 0.25 * stones)
    return save_set('asphalt', col, agg * 0.7 + stones * 0.3, 2.5, None, ft)


def gravel():
    N = 512; ft = 4.0
    r = rng(141); pts = r.uniform(0, N, (1400, 2)); yy, xx = np.mgrid[0:N, 0:N].astype(float)
    d1 = np.full((N, N), 1e9); idx = np.zeros((N, N), int)
    for i, (px, py) in enumerate(pts):
        dx = np.abs(xx - px); dx = np.minimum(dx, N - dx); dy = np.abs(yy - py); dy = np.minimum(dy, N - dy)
        d = dx * dx + dy * dy
        closer = d < d1; idx = np.where(closer, i, idx); d1 = np.where(closer, d, d1)
    tone = (1 + r.normal(0, 0.18, len(pts)))[idx]
    dome = np.clip(1 - np.sqrt(d1) / 9.0, 0, 1)
    col = shade(hex_rgb('#9a948a'), tone * (0.6 + 0.5 * dome))
    return save_set('gravel', col, dome, 5.0, None, ft)


def grass():
    """Lawn seen from standing height: dense blades, clumps, a little straw. 6 ft."""
    N = 1024; ft = 6.0
    blades = spectral(N, 1.4, 151, aniso=(1, 4))
    blades2 = spectral(N, 1.4, 152, aniso=(4, 1))
    clump = fbm(N, 25, 153)
    straw = (spectral(N, 3, 154) > 0.74).astype(float) * 0.5
    lum = 0.7 + 0.45 * np.maximum(blades, blades2) * (0.75 + 0.5 * clump)
    col = shade(hex_rgb('#5f8f3a'), lum) + straw[..., None] * np.array([0.12, 0.08, 0.0])
    return save_set('grass', col, np.maximum(blades, blades2), 2.0, None, ft)


